"""Sensitivity check: how much do the results depend on our guesses?

PROTOTYPE: everything here is SIMULATED.

Changes one assumption at a time, rebuilds the simulated days, retrains the
tree, and records what changes. Does not touch data/, model.pkl or the app.

Run from the project root:  python -m src.sensitivity
Output: docs/sensitivity.md
"""

from pathlib import Path

import pandas as pd
from sklearn.model_selection import StratifiedKFold, cross_val_score

from src.simulate import BATCH_SIZE, DAY_MULT, NOISE_SD, build_dataset
from src.train import CV_FOLDS, FEATURES, SEED, TARGET, make_tree

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "sensitivity.md"

# Each variant changes ONE assumption; everything else stays as in docs/assumptions.md.
VARIANTS = {
    "Base (current assumptions)": {},
    "Weekend 0.70 instead of 0.95": {"day_mult": {**DAY_MULT, "Saturday": 0.70, "Sunday": 0.70}},
    "Noise ±5% instead of ±10%": {"noise_sd": 0.05},
    "Noise ±15% instead of ±10%": {"noise_sd": 0.15},
    "Batch 350 instead of 400": {"batch_size": 350},
    "Batch 450 instead of 400": {"batch_size": 450},
}

# The 5 report scenarios plus a Saturday, so the weekend change shows up.
SCENARIOS = {
    "Normal Monday": ("Monday", "normal", "clear", "normal"),
    "Friday": ("Friday", "normal", "clear", "normal"),
    "Saturday": ("Saturday", "normal", "clear", "normal"),
    "Rainy day": ("Wednesday", "normal", "rainy", "normal"),
    "Exam week": ("Tuesday", "exam", "clear", "normal"),
    "Public holiday": ("Monday", "holiday", "clear", "light"),
}


def run_variant(overrides):
    df = build_dataset(**overrides)
    X, y = df[FEATURES], df[TARGET]
    folds = StratifiedKFold(n_splits=CV_FOLDS, shuffle=True, random_state=SEED)
    accuracy = cross_val_score(make_tree(), X, y, cv=folds).mean()

    model = make_tree().fit(X, y)  # all days, to predict the scenarios
    inputs = pd.DataFrame(list(SCENARIOS.values()), columns=FEATURES)
    predictions = dict(zip(SCENARIOS, model.predict(inputs)))

    share = y.value_counts(normalize=True)
    return {
        "accuracy": accuracy,
        "low": share.get("low", 0), "medium": share.get("medium", 0), "high": share.get("high", 0),
        **predictions,
    }


def main():
    results = {name: run_variant(o) for name, o in VARIANTS.items()}
    table = pd.DataFrame(results).T
    base = table.iloc[0]
    table["Scenarios changed"] = [
        sum(row[s] != base[s] for s in SCENARIOS) for _, row in table.iterrows()
    ]

    shown = table.copy()
    shown["CV accuracy"] = shown["accuracy"].map(lambda v: f"{v:.2f}")
    for c in ["low", "medium", "high"]:
        shown[f"% {c} days"] = shown[c].map(lambda v: f"{v:.0%}")
    data_cols = ["CV accuracy", "% low days", "% medium days", "% high days"]
    scenario_cols = list(SCENARIOS) + ["Scenarios changed"]

    md = f"""# Sensitivity check (SIMULATED)

Generated by `python -m src.sensitivity`. Each row changes **one** assumption,
rebuilds the {len(build_dataset())} simulated days, and retrains the tree. Base values:
weekend {DAY_MULT['Saturday']}, noise ±{NOISE_SD:.0%}, batch {BATCH_SIZE}.

## Effect on the data and the model

{shown[data_cols].to_markdown()}

## Effect on the predicted risk for each scenario

{shown[scenario_cols].to_markdown()}

"Scenarios changed" counts how many of the {len(SCENARIOS)} scenarios get a different
risk tier from the base row. A row with 0 means that guess doesn't change the advice.
"""
    OUTPUT.write_text(md)
    print(md)


if __name__ == "__main__":
    main()
