"""Run the 5 report test cases through the advisor and save a results table.

PROTOTYPE: results come from a model trained on SIMULATED data.

Run from the project root:  python -m src.scenarios
Outputs: docs/scenarios.csv and docs/scenarios.md (a table to paste into the report)
"""

from datetime import date
from pathlib import Path

import pandas as pd

from src.advisor import advise, load_model

DOCS = Path(__file__).resolve().parent.parent / "docs"

# (name, date, calendar, weather, class_load). Everything not being tested is
# kept at "normal" or "clear" so each case shows one effect.
SCENARIOS = [
    ("Normal Monday", date(2026, 3, 9), "normal", "clear", "normal"),
    ("Friday", date(2026, 3, 13), "normal", "clear", "normal"),
    ("Rainy day", date(2026, 3, 11), "normal", "rainy", "normal"),          # a Wednesday
    ("Exam week", date(2026, 4, 14), "exam", "clear", "normal"),            # a Tuesday
    ("Public holiday", date(2026, 8, 31), "holiday", "clear", "light"),     # National Day, a Monday; A11
]


def main():
    model = load_model()
    rows = []
    for name, day, calendar, weather, class_load in SCENARIOS:
        r = advise(model, day, calendar, weather, class_load)
        rows.append({
            "Scenario": name,
            "Date": f"{day:%a %d %b %Y}",
            "Calendar": calendar,
            "Weather": weather,
            "Class load": class_load,
            "Waste risk": r["risk"],
            "Confidence": f"{r['confidence']:.0%}",
            "Est. footfall": r["footfall"],
            "vs normal": f"{r['vs_normal']:+.0%}",
            "Suggested batch": r["suggested_batch"],
            "Change vs usual 400": f"{r['suggested_batch'] - r['usual_batch']:+d}",
        })
    table = pd.DataFrame(rows)

    DOCS.mkdir(exist_ok=True)
    table.to_csv(DOCS / "scenarios.csv", index=False)
    md = ("# Scenario results (SIMULATED)\n\n"
          "Generated by `python -m src.scenarios`. All results come from a model trained on "
          "simulated data; see `docs/assumptions.md`.\n\n"
          + table.to_markdown(index=False) + "\n")
    (DOCS / "scenarios.md").write_text(md)

    print("SIMULATED results\n")
    print(table.to_string(index=False))
    print(f"\nSaved -> {DOCS / 'scenarios.csv'} and {DOCS / 'scenarios.md'}")


if __name__ == "__main__":
    main()
